async function seedTwenty() {
  console.log(`Starting to insert ${twentyPlayers.length} requests into Supabase...`);
  let successCount = 0;

  for (const p of twentyPlayers) {
    const { data, error } = await supabase
      .from("player_registration_requests")
      .insert(p)
      .select()
      .single();

    if (error) {
      console.error(`❌ Error inserting ${p.player_name}:`, error.message);
    } else {
      successCount++;
      console.log(`[${successCount}/${twentyPlayers.length}] ✅ Inserted: ${data.player_name} (${data.current_club}) - Code: ${data.preferred_player_code}`);
    }
  }

  console.log(`\n🎉 Completed! Successfully inserted ${successCount} out of ${twentyPlayers.length} players.`);
}

